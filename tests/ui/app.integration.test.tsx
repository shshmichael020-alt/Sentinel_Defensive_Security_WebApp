import { describe, it, expect, vi, beforeEach, afterEach } from 'vitest';
import { render, screen } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { App } from '../../src/App';

describe('Sentinel UI Integration Tests', () => {
  beforeEach(() => {
    vi.stubGlobal('fetch', vi.fn().mockRejectedValue(new Error('Network offline')));
  });

  afterEach(() => {
    vi.restoreAllMocks();
  });

  it('loads with pre-analyzed defaults and visible executive KPI strip values', () => {
    render(<App />);

    // App header
    expect(screen.getByRole('heading', { level: 1, name: /sentinel/i })).toBeInTheDocument();

    // Privacy note
    expect(screen.getByText(/privacy guarantee:/i)).toBeInTheDocument();

    // 4 KPI cards
    expect(screen.getByText(/link risk/i)).toBeInTheDocument();
    expect(screen.getByText(/message risk/i)).toBeInTheDocument();
    expect(screen.getByText(/password strength/i)).toBeInTheDocument();
    expect(screen.getByText(/session posture/i)).toBeInTheDocument();

    // Active Link tab pre-loaded with preset
    expect(screen.getByDisplayValue(/paypa1-security-update\.xyz/i)).toBeInTheDocument();
  });

  it('supports tab switching and updates aria-selected attributes', async () => {
    const user = userEvent.setup();
    render(<App />);

    const linkTab = screen.getByRole('tab', { name: /link check/i });
    const messageTab = screen.getByRole('tab', { name: /message check/i });
    const passwordTab = screen.getByRole('tab', { name: /password check/i });

    expect(linkTab).toHaveAttribute('aria-selected', 'true');
    expect(messageTab).toHaveAttribute('aria-selected', 'false');

    await user.click(messageTab);
    expect(messageTab).toHaveAttribute('aria-selected', 'true');
    expect(linkTab).toHaveAttribute('aria-selected', 'false');
    expect(screen.getByLabelText(/suspicious message content/i)).toBeInTheDocument();

    await user.click(passwordTab);
    expect(passwordTab).toHaveAttribute('aria-selected', 'true');
    expect(screen.getByLabelText(/password resilience & defense check/i)).toBeInTheDocument();
  });

  it('typing a lookalike URL raises a critical signal pill and attack anatomy tag', async () => {
    const user = userEvent.setup();
    render(<App />);

    const input = screen.getByLabelText(/target web address/i);
    await user.clear(input);
    await user.type(input, 'https://paypa1.com/login');

    expect(screen.getByText(/brand typo \/ lookalike domain/i)).toBeInTheDocument();
    expect(screen.getAllByText(/critical/i).length).toBeGreaterThan(0);
  });

  it('message tab preset displays highlighted <mark> tags on flagged phrases', async () => {
    const user = userEvent.setup();
    render(<App />);

    const messageTab = screen.getByRole('tab', { name: /message check/i });
    await user.click(messageTab);

    // Default message preset has OTP and threat
    const marks = document.querySelectorAll('mark');
    expect(marks.length).toBeGreaterThan(0);
    expect(screen.getByText(/social engineering highlights/i)).toBeInTheDocument();
  });

  it('toggles password input show/hide and updates aria-pressed', async () => {
    const user = userEvent.setup();
    render(<App />);

    const passwordTab = screen.getByRole('tab', { name: /password check/i });
    await user.click(passwordTab);

    const toggleBtn = screen.getByRole('button', { name: /show password/i });
    expect(toggleBtn).toHaveAttribute('aria-pressed', 'false');

    await user.click(toggleBtn);
    expect(screen.getByRole('button', { name: /hide password/i })).toHaveAttribute('aria-pressed', 'true');
  });

  it('learn tab allows answering drills and reveals engine verdict', async () => {
    const user = userEvent.setup();
    render(<App />);

    const learnTab = screen.getByRole('tab', { name: /learn & emergency/i });
    await user.click(learnTab);

    expect(screen.getByRole('heading', { level: 3, name: /spot the scam drill/i })).toBeInTheDocument();

    const scamBtn = screen.getByRole('button', { name: /mark as phishing \/ scam/i });
    await user.click(scamBtn);

    // After answering, verdict is revealed
    expect(screen.getByText(/sentinel engine:/i)).toBeInTheDocument();
    expect(screen.getByRole('button', { name: /next drill/i })).toBeInTheDocument();
  });

  it('explain panel falls back gracefully to rule-engine explanation when API fails', async () => {
    const user = userEvent.setup();
    render(<App />);

    const explainBtn = screen.getByRole('button', { name: /explain in plain language/i });
    await user.click(explainBtn);

    expect(
      await screen.findByText(/generated by sentinel’s rule engine/i),
    ).toBeInTheDocument();
  });
});
