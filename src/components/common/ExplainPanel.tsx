import type { FC } from 'react';
import type { Severity, Verdict } from '@/types/severity';
import { useExplain } from '@/hooks/useExplain';
import { RefreshCw, Sparkles, CheckCircle2 } from 'lucide-react';

export interface ExplainPanelProps {
  readonly kind: 'link' | 'message';
  readonly score: number;
  readonly verdict: Verdict;
  readonly signals: readonly { readonly id: string; readonly severity: Severity }[];
}

const ExplainResultBox: FC<{ readonly text: string; readonly source: 'ai' | 'fallback' | null }> = ({
  text,
  source,
}) => (
  <div className="mt-1 flex flex-col gap-1.5 p-3 bg-blue-50/50 rounded border border-blue-100 text-xs text-sentinel-ink leading-relaxed">
    <p>{text}</p>
    <div className="flex items-center gap-1 text-[11px] text-sentinel-secondary mt-1">
      <CheckCircle2 size={12} className="text-blue-600 shrink-0" aria-hidden="true" />
      <span>
        {source === 'ai'
          ? 'Generated by AI from Sentinel’s computed signals'
          : 'Generated by Sentinel’s rule engine'}
      </span>
    </div>
  </div>
);

const ExplainTriggerButton: FC<{ readonly isLoading: boolean; readonly onClick: () => void }> = ({
  isLoading,
  onClick,
}) => (
  <button
    type="button"
    onClick={onClick}
    disabled={isLoading}
    className="inline-flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium rounded-md bg-white border border-slate-300 text-sentinel-ink hover:bg-slate-50 focus-visible:ring-2 focus-visible:ring-blue-600 transition-colors disabled:opacity-50"
  >
    {isLoading ? (
      <>
        <RefreshCw size={12} className="animate-spin text-blue-600" aria-hidden="true" />
        <span>Analyzing signals...</span>
      </>
    ) : (
      <span>Explain in plain language</span>
    )}
  </button>
);

export const ExplainPanel: FC<ExplainPanelProps> = ({ kind, score, verdict, signals }) => {
  const { explanation, source, isLoading, requestExplanation } = useExplain();

  return (
    <div className="flex flex-col gap-2.5 p-3.5 rounded-lg border border-slate-200 bg-white">
      <div className="flex items-center justify-between gap-2 flex-wrap">
        <span className="text-xs font-semibold text-sentinel-secondary flex items-center gap-1.5">
          <Sparkles size={14} className="text-blue-600" aria-hidden="true" />
          <span>Need a simple summary?</span>
        </span>
        <ExplainTriggerButton
          isLoading={isLoading}
          onClick={() => { void requestExplanation(kind, score, verdict, signals); }}
        />
      </div>

      <div aria-live="polite">
        {explanation && <ExplainResultBox text={explanation} source={source} />}
      </div>
    </div>
  );
};

